package com.ailms.entity.enums;

/**
 * Quản lý trạng thái lời mời giảng dạy giữa các giảng viên trong dự án
 * PENDING: đang chờ
 * ACCEPTED: ĐỒng ý, giảng viên được mời chấp nhận tham gia khóa học
 * REJECTED: từ chối tham gia phát triển khóa học đó
 */
public enum CourseInstructorStatusEnum {
    PENDING,
    ACCEPTED,
    REJECTED
}
